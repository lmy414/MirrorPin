/** 获取某字符字模，未知字符返回空格 */
export function glyph(ch: string): string[] {
  return GLYPH.get(ch.toUpperCase()) ?? ['.....', '.....', '.....', '.....', '.....', '.....', '.....'];
}

/** 文本宽度（格数）：每字符 6 宽（5 字宽 + 1 间距） */
export function textWidth(text: string): number {
  if (text.length === 0) return 0;
  return text.length * 6 - 1;
}